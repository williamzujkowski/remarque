/*
 * Font-feature check (issue #124, ratified 7-0 in vote-1792819660668-a5kb6q3).
 *
 * CSS can ask for typographic features the font doesn't have, and nothing
 * fails: `font-variant-caps: all-small-caps` on a face with no smcp/c2sc
 * makes the browser SYNTHESIZE small caps by shrinking capitals (a 14px
 * label drew its caps at ~9.9px, under the 13px floor), and
 * `oldstyle-nums` on a face with no onum renders lining figures. Until
 * 0.28 the spec claimed both on the default stack, which has neither.
 *
 * This module reads a feature manifest (fonts/features.json: OpenType
 * GSUB+GPOS tags per shipped face, generated by scripts/font-features.py)
 * and checks every feature request in a stylesheet against the face the
 * rule's `font-family` resolves to.
 *
 *   - ok:            the face has the feature, or its default glyphs
 *                    already are what was asked for (lining figures need no
 *                    lnum; a tabular-by-default face needs no tnum).
 *   - missing:       the face lacks it and the rule doesn't say that's
 *                    expected. A FAILURE.
 *   - conditional:   the face lacks it, but the rule carries a
 *                    `remarque-feature: conditional` comment: an
 *                    enhancement that renders on faces that have it (the
 *                    flagship's Source Serif 4 has onum) and is a no-op
 *                    elsewhere. Reported, never a failure.
 *   - unverifiable:  the face isn't in the manifest (a consumer face with
 *                    no manifest entry). Reported, never a failure.
 *
 * Rules without their own `font-family` are checked against --font-body,
 * the face they inherit in a Remarque page. Consumers add their faces with
 * `remarque-audit --font-features <manifest.json>` (same shape), merged
 * over the package's own manifest.
 */

// font-variant-* keyword -> OpenType tags it needs
const CAPS = {
  'small-caps': ['smcp'],
  'all-small-caps': ['smcp', 'c2sc'],
  'petite-caps': ['pcap'],
  'all-petite-caps': ['pcap', 'c2pc'],
  unicase: ['unic'],
  'titling-caps': ['titl'],
};
const NUMERIC = {
  'oldstyle-nums': 'onum',
  'lining-nums': 'lnum',
  'tabular-nums': 'tnum',
  'proportional-nums': 'pnum',
  'diagonal-fractions': 'frac',
  'stacked-fractions': 'afrc',
  ordinal: 'ordn',
  'slashed-zero': 'zero',
};
// Requests a face's default glyphs satisfy with no feature at all.
function satisfiedByDefault(tag, figures) {
  if (!figures) return false;
  if (tag === 'lnum') return figures.style === 'lining';
  if (tag === 'onum') return figures.style === 'oldstyle';
  if (tag === 'tnum') return figures.spacing === 'tabular';
  if (tag === 'pnum') return figures.spacing === 'proportional';
  return false;
}

const CONDITIONAL = /remarque-feature:\s*conditional/;

/* Leaf rule blocks ({ } with no nested braces) with their line, selector,
   raw body (comments kept, for the annotation) and stripped body. */
function leafRules(css) {
  const out = [];
  const re = /([^{}]*)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const lead = m[1];
    const selector = lead.replace(/\/\*[\s\S]*?\*\//g, '').trim();
    if (!selector || selector.startsWith('@')) continue;
    const line = css.slice(0, m.index + lead.length).split('\n').length;
    out.push({ selector, line, raw: m[2], body: m[2].replace(/\/\*[\s\S]*?\*\//g, '') });
  }
  return out;
}

function declValues(body, prop) {
  const vals = [];
  for (const m of body.matchAll(new RegExp(`(?:^|[;\\s])${prop}\\s*:\\s*([^;]+)`, 'g'))) vals.push(m[1].trim());
  return vals;
}

/* Every feature a rule asks for, as [{ tag, via }]. */
function requestsOf(body) {
  const req = [];
  for (const v of declValues(body, 'font-variant-caps')) for (const t of CAPS[v] || []) req.push({ tag: t, via: `font-variant-caps: ${v}` });
  for (const v of declValues(body, 'font-variant-numeric'))
    for (const kw of v.split(/\s+/)) if (NUMERIC[kw]) req.push({ tag: NUMERIC[kw], via: `font-variant-numeric: ${kw}` });
  for (const v of declValues(body, 'font-variant'))
    for (const kw of v.split(/\s+/)) {
      for (const t of CAPS[kw] || []) req.push({ tag: t, via: `font-variant: ${kw}` });
      if (NUMERIC[kw]) req.push({ tag: NUMERIC[kw], via: `font-variant: ${kw}` });
    }
  for (const v of declValues(body, 'font-feature-settings'))
    for (const m of v.matchAll(/["']([a-zA-Z0-9]{4})["']\s*(on|off|\d+)?/g))
      if (m[2] !== 'off' && m[2] !== '0') req.push({ tag: m[1], via: `font-feature-settings: "${m[1]}"` });
  return req;
}

/* The family a rule renders in: its own font-family (a var(--font-*) token
   resolved through `fontStacks`, or a literal stack), else --font-body. */
function familyOf(body, fontStacks) {
  const ff = declValues(body, 'font-family').pop();
  const stack = !ff ? fontStacks['--font-body'] : ff.startsWith('var(') ? fontStacks[(ff.match(/var\(\s*(--[\w-]+)/) || [])[1]] : ff;
  if (!stack) return { family: null, inferred: !ff };
  const first = stack.split(',')[0].trim().replace(/^["']|["']$/g, '');
  return { family: first, inferred: !ff };
}

/**
 * @param {string} css            stylesheet text
 * @param {object} manifest       { families: { [name]: { figures, files: { [f]: { features } } } } }
 * @param {object} fontStacks     { '--font-body': '"Inter", ...', ... }
 * @returns {Array<{line, selector, family, inferred, tag, via, status}>}
 */
export function checkFontFeatures(css, manifest, fontStacks) {
  const results = [];
  for (const rule of leafRules(css)) {
    const reqs = requestsOf(rule.body);
    if (!reqs.length) continue;
    const { family, inferred } = familyOf(rule.body, fontStacks);
    const entry = family && manifest.families?.[family];
    const conditional = CONDITIONAL.test(rule.raw);
    for (const r of reqs) {
      let status;
      if (!entry) status = 'unverifiable';
      else {
        // Every file of the family (roman and italic) must have it.
        const has = Object.values(entry.files).every((f) => f.features.includes(r.tag));
        status = has || satisfiedByDefault(r.tag, entry.figures) ? 'ok' : conditional ? 'conditional' : 'missing';
      }
      results.push({ line: rule.line, selector: rule.selector.replace(/\s+/g, ' ').slice(0, 100), family, inferred, ...r, status });
    }
  }
  return results;
}

/* Merge consumer manifests over the package's (consumer entries win). */
export function mergeManifests(...ms) {
  const families = {};
  for (const m of ms) Object.assign(families, m?.families || {});
  return { families };
}
