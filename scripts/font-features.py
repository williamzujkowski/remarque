#!/usr/bin/env python3
"""Regenerate fonts/features.json from the shipped woff2 files (issue #124).

remarque-audit's font-feature check reads that manifest to tell whether a
CSS feature request (small caps, oldstyle figures, font-feature-settings)
can render on the face it targets. Run this whenever fonts/ is re-subset:

    python3 scripts/font-features.py

Needs fontTools with brotli (pip install fonttools brotli). It isn't run in
CI; scripts/test-font-features.mjs fails if a woff2's sha256 no longer
matches the manifest, so a re-subset without a regeneration can't land.

The `figures` field is the face's DEFAULT figure style, which the gate
needs because a lining-by-default face satisfies `lining-nums` with no
`lnum` feature, and a monospaced face satisfies `tabular-nums` with no
`tnum`. fontTools can't tell those from the tables reliably, so they're
taken from FIGURES below (measured in a browser; see the PR for #124).
"""
import hashlib, json, pathlib, re
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts"
CSS = (ROOT / "fonts.css").read_text()

# family -> default figures, measured in Chromium (2026-10-24): "1" vs "0"
# advance ratio with no features (Inter 0.65 = proportional; Newsreader and
# JetBrains Mono 1.0 = tabular), and digit heights (3 = 8 = 0: lining).
FIGURES = {
    "Inter": {"style": "lining", "spacing": "proportional"},
    "Newsreader": {"style": "lining", "spacing": "tabular"},
    "JetBrains Mono": {"style": "lining", "spacing": "tabular"},
}

def features(font):
    tags = set()
    for t in ("GSUB", "GPOS"):
        if t in font and font[t].table.FeatureList:
            tags.update(r.FeatureTag for r in font[t].table.FeatureList.FeatureRecord)
    return sorted(tags)

families = {}
for block in re.findall(r"@font-face\s*\{(.*?)\}", CSS, re.S):
    fam = re.search(r'font-family:\s*"([^"]+)"', block).group(1)
    style = re.search(r"font-style:\s*(\w+)", block).group(1)
    src = re.search(r'url\("fonts/([^"]+)"\)', block).group(1)
    data = (FONTS / src).read_bytes()
    entry = families.setdefault(fam, {"files": {}, "figures": FIGURES[fam]})
    entry["files"][src] = {
        "style": style,
        "sha256": hashlib.sha256(data).hexdigest(),
        "features": features(TTFont(FONTS / src)),
    }

out = {
    "$comment": "GENERATED by scripts/font-features.py from fonts/*.woff2 -- do not hand-edit. "
                "OpenType GSUB+GPOS feature tags per shipped face, read by remarque-audit's font-feature check (#124).",
    "families": families,
}
(FONTS / "features.json").write_text(json.dumps(out, indent=2) + "\n")
print(f"fonts/features.json: {sum(len(f['files']) for f in families.values())} files, {len(families)} families")
